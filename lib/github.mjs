// `wf github sync | check | ruleset`: the project's GitHub files, from the
// `github` key in its config (audit W-12). What a plan can enforce differs, so
// each file has its own switch; a solo project on a free private repository
// turns on only what helps one person. `sync` writes the files that are on and
// removes generated ones that are off, `check` fails on any that drifted, and
// `ruleset` prints the ruleset to apply with gh, since a ruleset is a setting,
// not a file.

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const MARK = "Generated by wf github sync from .workflow/config.json; change the config, not this file.";

/** Who holds a role, as GitHub handles with @. */
export function holders(config, role) {
  return (config.people ?? []).filter((person) => (person.roles ?? []).some((held) => held === role || held.startsWith(`${role}:`))).map((person) => `@${person.handle}`).filter((handle) => handle !== "@undefined");
}

function prTemplate(config) {
  return `<!-- ${MARK} -->
<!-- The title is the commit subject: "<scope>: <what changed>". The body is the commit body: one bullet per ID, ID first. -->

Track: <!-- quick, chunk, or area -->

- <ID>: <what changed and why>

## Needs

<!-- One line per question waiting on someone who holds a role, ticked when answered. \`npx wf signoffs\` lists the open ones, and the pull-request skill will not propose a merge while any are open. -->
<!-- - [ ] needs designer: <question> -->
`;
}

function storyTemplate() {
  return `---
name: Story
about: Something a user should be able to do
---
<!-- ${MARK} -->

As a <who>, I want <what>, so that <why>.

**Acceptance**

- <a line a person can check on screen>
`;
}

function bugTemplate() {
  return `---
name: Bug
about: Something that works differently from its story
---
<!-- ${MARK} -->

**Story:** <ID, if one covers it>

**Steps**

1. <from a fresh start>

**What happened**

**What the story says should happen**
`;
}

function codeowners(config) {
  const line = (pattern, roles) => {
    const handles = [...new Set(roles.flatMap((role) => holders(config, role)))];
    return handles.length ? `${pattern} ${handles.join(" ")}` : null;
  };
  const design = config.design ?? {};
  return [
    `# ${MARK}`,
    "# The last matching line wins. Owners come from people and their roles.",
    line("*", ["reviewer"]),
    design.frames ? line(`/${design.frames}/`, ["designer"]) : null,
    design.review ? line(`/${design.review}/`, ["designer"]) : null,
    line("/.workflow/", ["owner"]),
    line(`/${config.docs?.workflow ?? "docs/workflow"}/`, ["owner"]),
    "",
  ]
    .filter((entry) => entry !== null)
    .join("\n");
}

function checkWorkflow(config) {
  const { command, setup } = config.github.check;
  return `# ${MARK}
name: Check
on:
  pull_request:
permissions:
  contents: read
jobs:
  check:
    runs-on: ubuntu-24.04
    steps:
      - uses: actions/checkout@v4
${setup.map((step) => `      - run: ${step}\n`).join("")}      - run: ${command}
`;
}

/** Dependabot's ecosystems, from the files the project holds. */
export function ecosystems(root) {
  const found = [];
  if (existsSync(join(root, "package.json"))) found.push("npm");
  if (existsSync(join(root, "Cargo.toml"))) found.push("cargo");
  if (existsSync(join(root, "pyproject.toml")) || existsSync(join(root, "requirements.txt"))) found.push("pip");
  if (existsSync(join(root, ".github/workflows"))) found.push("github-actions");
  return found;
}

function dependabot(root) {
  return `# ${MARK}
version: 2
updates:
${ecosystems(root).map((name) => `  - package-ecosystem: ${name}\n    directory: /\n    schedule:\n      interval: weekly\n`).join("")}`;
}

/** Every file the kit can generate, with its switch and its text. */
export function githubFiles(root, config) {
  const on = config.github;
  return [
    [".github/pull_request_template.md", on.prTemplate, () => prTemplate(config)],
    [".github/ISSUE_TEMPLATE/story.md", on.issueTemplates, storyTemplate],
    [".github/ISSUE_TEMPLATE/bug.md", on.issueTemplates, bugTemplate],
    [".github/CODEOWNERS", on.codeowners, () => codeowners(config)],
    [".github/workflows/check.yml", on.checkWorkflow, () => checkWorkflow(config)],
    [".github/dependabot.yml", on.dependabot, () => dependabot(root)],
  ];
}

/** Compare, or with `write` bring in step, every generated file. Returns the problems and how many changed. */
export function syncGithub(root, config, { write = false } = {}) {
  if (config.github.checkWorkflow && !config.github.check.command) {
    return { problems: ["github.check.command is empty: the check workflow needs the command it runs"], changed: 0 };
  }
  const problems = [];
  let changed = 0;
  for (const [path, enabled, text] of githubFiles(root, config)) {
    const file = join(root, path);
    const current = existsSync(file) ? readFileSync(file, "utf8") : null;
    const generated = current?.includes(MARK);
    if (enabled) {
      const want = text();
      if (current === want) continue;
      if (current !== null && !generated) problems.push(`${path}: hand-written; delete it or turn its github switch off`);
      else if (write) {
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, want);
        changed += 1;
      } else problems.push(`${path}: ${current === null ? "missing" : "out of date"}, run wf github sync`);
    } else if (generated) {
      if (write) {
        rmSync(file);
        changed += 1;
      } else problems.push(`${path}: its github switch is off, run wf github sync to remove it`);
    }
  }
  return { problems, changed };
}

/** The ruleset for the default branch, for `gh api repos/{owner}/{repo}/rulesets -X POST --input -`. */
export function ruleset(config) {
  const approvals = config.team === "solo" ? 0 : 1;
  const rules = [
    { type: "deletion" },
    { type: "non_fast_forward" },
    // Squash only, as branches.md says, so main reads one commit per pull request.
    { type: "pull_request", parameters: { required_approving_review_count: approvals, dismiss_stale_reviews_on_push: true, require_code_owner_review: Boolean(config.github.codeowners), require_last_push_approval: approvals > 0, required_review_thread_resolution: false, allowed_merge_methods: ["squash"] } },
  ];
  if (config.github.checkWorkflow) rules.push({ type: "required_status_checks", parameters: { strict_required_status_checks_policy: false, required_status_checks: [{ context: "check" }] } });
  const set = { name: "main", target: "branch", enforcement: "active", conditions: { ref_name: { include: ["~DEFAULT_BRANCH"], exclude: [] } }, rules };
  // Organization admins may merge a pull request past the rules, such as a sole reviewer's own; they still cannot push to main.
  if (config.github.adminBypass) set.bypass_actors = [{ actor_id: 1, actor_type: "OrganizationAdmin", bypass_mode: "pull_request" }];
  return set;
}

/** Why the plan cannot hold a ruleset, or null when it can. */
export function rulesetBlocked(config) {
  const { plan, public: open } = config.github;
  return plan === "free" && !open ? "a private repository on the free plan has no rulesets or branch protection; the local git hooks and the pull-request skill hold the rules" : null;
}
