/** Every setting's path, and whether its value is an open map whose entries share its line. */
export function settingPaths(defaults, open, prefix = "") {
  const out = [];
  for (const [key, value] of Object.entries(defaults)) {
    const path = prefix ? `${prefix}.${key}` : key;
    out.push(path);
    const nested = value && typeof value === "object" && !Array.isArray(value) && Object.keys(value).length;
    if (nested && !open.has(path)) out.push(...settingPaths(value, open, path));
  }
  return out;
}
