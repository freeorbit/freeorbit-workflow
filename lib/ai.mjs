// Keeps OpenCode in step with what Claude Code reads. Agents come from the
// project's .claude/agents and from each kit plugin's agents/; OpenCode gets a
// native copy of each in .opencode/agents. A skill marked
// `disable-model-invocation` gets a slash command in .opencode/commands, and
// opencode.json lists every kit plugin's skills folder.

import { existsSync, readFileSync, realpathSync } from "node:fs";
import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const KIT_ROOT = fileURLToPath(new URL("../", import.meta.url));
export const MARKER = "# Generated by wf ai:sync; do not edit.";
// Files the adapter wrote before it moved into the kit count as generated too.
const OLD_MARKERS = ["# Generated by tools/ai/adapters.mjs; do not edit."];
const generated = (text) => [MARKER, ...OLD_MARKERS].some((marker) => text.includes(marker));
const SUPPORTED_FIELDS = new Set(["name", "description", "model", "tools"]);
// OpenCode applies the last matching rule, so these follow the read allow to keep its built-in .env rules.
const READ_GUARDS = [
  ["*.env", "ask"],
  ["*.env.*", "ask"],
  ["*.env.example", "allow"],
];

export const TOOL_ACTIONS = {
  Read: "read",
  Grep: "grep",
  Glob: "glob",
  WebFetch: "webfetch",
  WebSearch: "websearch",
  Bash: "shell",
  Edit: "edit",
  Write: "edit",
  Skill: "skill",
  Agent: "subagent",
  Task: "subagent",
};

/** A canonical agent file as { name, description (its raw frontmatter lines), tools, body }. Throws on anything OpenCode cannot carry. */
export function parseAgent(markdown, filename = "agent.md") {
  const lines = markdown.replaceAll("\r\n", "\n").split("\n");
  if (lines[0] !== "---") throw new Error(`${filename}: frontmatter must start on line 1`);
  const close = lines.indexOf("---", 1);
  if (close === -1) throw new Error(`${filename}: frontmatter is not closed`);

  const fields = new Map();
  for (let index = 1; index < close; index += 1) {
    const match = lines[index].match(/^([A-Za-z][A-Za-z0-9_-]*):[ \t]*(.*)$/);
    if (!match) throw new Error(`${filename}: unsupported frontmatter line ${index + 1}`);
    const [, key, firstValue] = match;
    if (!SUPPORTED_FIELDS.has(key)) throw new Error(`${filename}: ${key} needs an explicit OpenCode adapter mapping`);
    if (fields.has(key)) throw new Error(`${filename}: duplicate ${key} field`);
    const raw = [lines[index]];
    if (/^[>|][+-]?$/.test(firstValue)) {
      while (index + 1 < close && (/^[ \t]+/.test(lines[index + 1]) || lines[index + 1] === "")) {
        index += 1;
        raw.push(lines[index]);
      }
    }
    fields.set(key, { value: firstValue.trim(), raw });
  }

  for (const required of ["name", "description", "tools"]) {
    if (!fields.has(required)) throw new Error(`${filename}: missing ${required}`);
  }
  const model = fields.get("model")?.value ?? "inherit";
  if (model !== "inherit") throw new Error(`${filename}: only model: inherit is portable; route native overrides at invocation`);

  const tools = fields.get("tools").value.split(",").map((tool) => tool.trim()).filter(Boolean);
  if (tools.length === 0) throw new Error(`${filename}: tools must not be empty`);
  for (const tool of tools) if (!TOOL_ACTIONS[tool]) throw new Error(`${filename}: no OpenCode permission mapping for ${tool}`);

  return { name: fields.get("name").value, description: fields.get("description").raw, tools, body: lines.slice(close + 1).join("\n") };
}

function permissionRule(action, resource, effect) {
  return [`  - action: ${action}`, `    resource: "${resource}"`, `    effect: ${effect}`];
}

/** A parsed agent as an OpenCode subagent that denies every action it does not list. */
export function renderAgent(agent) {
  const actions = [...new Set(agent.tools.map((tool) => TOOL_ACTIONS[tool]))];
  const frontmatter = [
    "---",
    MARKER,
    ...agent.description,
    "mode: subagent",
    "permissions:",
    '  - action: "*"',
    '    resource: "*"',
    "    effect: deny",
    ...actions.flatMap((action) => [
      ...permissionRule(action, "*", "allow"),
      ...(action === "read" ? READ_GUARDS.flatMap(([resource, effect]) => permissionRule(action, resource, effect)) : []),
    ]),
    "---",
  ];
  return `${frontmatter.join("\n")}\n${agent.body}`;
}

/** A skill's id, description as one line, and whether only a person may start it. */
export function parseSkill(markdown) {
  const front = markdown.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
  const description = (front.match(/^description:[ \t]*(?:>-?|\|-?)?[ \t]*\n?((?:[ \t]+.*\n?)+|.*)/m)?.[1] ?? "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .join(" ");
  return { description, manual: /^disable-model-invocation:[ \t]*true\b/m.test(front) };
}

/** An OpenCode slash command that loads the skill `id`. */
export function renderCommand(id, description) {
  return `---\n${MARKER}\ndescription: ${JSON.stringify(description)}\n---\n\nLoad the \`${id}\` skill with the \`skill\` tool and follow its instructions.\n`;
}

async function folders(dir) {
  if (!existsSync(dir)) return [];
  return (await readdir(dir, { withFileTypes: true })).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
}

/** The kit's plugin folders that hold something, as [name, path]. */
async function kitPlugins(kitRoot) {
  return (await folders(path.join(kitRoot, "plugins"))).map((name) => [name, path.join(kitRoot, "plugins", name)]);
}

/** The kit as the project reaches it: its node_modules link when that is this kit, so a path survives an upgrade. */
export function kitFrom(root, kitRoot) {
  const name = JSON.parse(readFileSync(path.join(kitRoot, "package.json"), "utf8")).name;
  const link = path.join(root, "node_modules", name);
  return existsSync(link) && realpathSync(link) === realpathSync(kitRoot) ? link : kitRoot;
}

/** Every file ai:sync owns, as { agents, commands, skillPaths }. Throws on a name clash or a bad source. */
export async function plan(root, kitRoot = KIT_ROOT) {
  kitRoot = kitFrom(root, kitRoot);
  const agentSources = [path.join(root, ".claude", "agents")];
  const skillSources = [path.join(root, ".claude", "skills")];
  const skillPaths = [];
  for (const [, dir] of await kitPlugins(kitRoot)) {
    agentSources.push(path.join(dir, "agents"));
    if (existsSync(path.join(dir, "skills"))) {
      skillSources.push(path.join(dir, "skills"));
      skillPaths.push(path.relative(root, path.join(dir, "skills")).split(path.sep).join("/"));
    }
  }
  const agents = new Map();
  for (const dir of agentSources.filter((d) => existsSync(d))) {
    for (const entry of (await readdir(dir)).filter((name) => name.endsWith(".md")).sort()) {
      const agent = parseAgent(await readFile(path.join(dir, entry), "utf8"), entry);
      if (agent.name !== entry.slice(0, -3)) throw new Error(`${entry}: name must match the filename (${entry.slice(0, -3)})`);
      // A project agent beats a plugin agent of the same name in Claude Code, so two sources would quietly differ.
      if (agents.has(entry)) throw new Error(`${entry}: defined in two places; delete the project copy once the kit has it`);
      agents.set(entry, renderAgent(agent));
    }
  }
  const commands = new Map();
  for (const dir of skillSources) {
    for (const id of await folders(dir)) {
      const file = path.join(dir, id, "SKILL.md");
      if (!existsSync(file)) continue;
      const skill = parseSkill(await readFile(file, "utf8"));
      if (skill.manual) commands.set(`${id}.md`, renderCommand(id, skill.description));
    }
  }
  return { agents, commands, skillPaths };
}

async function readOr(file, fallback = null) {
  return readFile(file, "utf8").catch((error) => {
    if (error.code === "ENOENT") return fallback;
    throw error;
  });
}

/** The differences between the planned files and the project, as problems; with `write`, fixes them instead. */
export async function reconcile(root, { write = false, kitRoot = KIT_ROOT } = {}) {
  const { agents, commands, skillPaths } = await plan(root, kitRoot);
  const problems = [];
  let changed = 0;
  for (const [folder, expected] of [["agents", agents], ["commands", commands]]) {
    const out = path.join(root, ".opencode", folder);
    if (write) await mkdir(out, { recursive: true });
    for (const [name, content] of expected) {
      const current = await readOr(path.join(out, name));
      if (current === content) continue;
      if (current !== null && !generated(current)) {
        problems.push(`.opencode/${folder}/${name}: hand-written, and the kit would generate it; delete it`);
      } else if (write) {
        await writeFile(path.join(out, name), content);
        changed += 1;
      } else problems.push(`.opencode/${folder}/${name}: ${current === null ? "missing" : "stale or edited directly"}`);
    }
    const present = existsSync(out) ? (await readdir(out)).filter((name) => name.endsWith(".md")) : [];
    for (const name of present.filter((n) => !expected.has(n))) {
      if (!generated(await readFile(path.join(out, name), "utf8"))) continue;
      if (write) {
        await rm(path.join(out, name));
        changed += 1;
      } else problems.push(`.opencode/${folder}/${name}: generated, but its source is gone`);
    }
  }
  const configPath = path.join(root, "opencode.json");
  const config = JSON.parse(await readOr(configPath, "{}"));
  const missing = skillPaths.filter((p) => !(config.skills ?? []).includes(p));
  if (missing.length && write) {
    config.$schema ??= "https://opencode.ai/config.json";
    config.skills = [...(config.skills ?? []), ...missing];
    await writeFile(configPath, `${JSON.stringify(config, null, 2)}\n`);
    changed += 1;
  } else for (const p of missing) problems.push(`opencode.json: skills does not list ${p}`);
  return { problems, changed, counts: { agents: agents.size, commands: commands.size } };
}
