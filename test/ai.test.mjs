import assert from "node:assert/strict";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { symlink } from "node:fs/promises";

import { parseAgent, parseSkill, reconcile, renderAgent } from "../lib/ai.mjs";

const source = `---
name: sample-agent
description: >-
  Reviews sample code and reports findings.
  Never edits files.
model: inherit
tools: Read, Grep, WebFetch, WebSearch
---

# Sample agent

Review only.
`;

test("renders a native OpenCode subagent and preserves its prompt", () => {
  const rendered = renderAgent(parseAgent(source, "sample-agent.md"));
  assert.match(rendered, /^---\n# Generated by wf ai:sync/);
  assert.match(rendered, /description: >-\n  Reviews sample code and reports findings\.\n  Never edits files\./);
  assert.match(rendered, /mode: subagent/);
  assert.match(rendered, /  - action: read\n    resource: "\*"\n    effect: allow/);
  assert.match(rendered, /  - action: websearch/);
  assert.ok(rendered.endsWith("\n# Sample agent\n\nReview only.\n"));

  const frontmatter = rendered.split("---")[1];
  assert.doesNotMatch(frontmatter, /^name:|^model:|^tools:/m);
  assert.ok(frontmatter.indexOf("effect: deny") < frontmatter.indexOf("effect: allow"));
});

test("denies the secret files after each read, grep, and glob allow, from the guard's one list", () => {
  const rendered = renderAgent(parseAgent(source, "sample-agent.md"));
  const readAllow = rendered.indexOf('action: read\n    resource: "*"\n    effect: allow');
  const envDeny = rendered.indexOf('action: read\n    resource: "*.env"\n    effect: deny');
  const keyDeny = rendered.indexOf('action: read\n    resource: "*.key"\n    effect: deny');
  const sshDeny = rendered.indexOf('action: read\n    resource: "*id_ed25519*"\n    effect: deny');
  assert.ok(readAllow !== -1 && readAllow < envDeny && envDeny < keyDeny && keyDeny < sshDeny);
  assert.match(rendered, /action: grep\n {4}resource: "\*\.pem"\n {4}effect: deny/);
  assert.doesNotMatch(rendered, /effect: ask|\.env\.example/);

  const withoutRead = renderAgent(parseAgent(source.replace("Read, Grep, WebFetch, WebSearch", "WebFetch"), "sample-agent.md"));
  assert.doesNotMatch(withoutRead, /\.env/);
});

test("deduplicates OpenCode actions for equivalent Claude tools", () => {
  const agent = parseAgent(source.replace("Read, Grep, WebFetch, WebSearch", "Edit, Write"));
  const rendered = renderAgent(agent);
  assert.equal(rendered.match(/  - action: edit/g).length, 1);
});

test("rejects a model that would not be portable", () => {
  assert.throws(
    () => parseAgent(source.replace("model: inherit", "model: sonnet"), "sample-agent.md"),
    /only model: inherit is portable/,
  );
});

test("rejects unknown fields instead of silently dropping behavior", () => {
  assert.throws(
    () => parseAgent(source.replace("model: inherit", "model: inherit\npermissionMode: plan"), "sample-agent.md"),
    /permissionMode needs an explicit OpenCode adapter mapping/,
  );
});

test("rejects tools without an explicit permission mapping", () => {
  assert.throws(
    () => parseAgent(source.replace("Read, Grep, WebFetch, WebSearch", "Read, NotebookEdit"), "sample-agent.md"),
    /no OpenCode permission mapping for NotebookEdit/,
  );
});


/** A throwaway project and kit: agents and skills in each, as { root, kit }. */
async function fixture(t, { projectAgents = {}, kitAgents = {}, kitSkills = {}, opencode } = {}) {
  const base = await mkdtemp(path.join(os.tmpdir(), "wf-ai-"));
  t.after(() => rm(base, { recursive: true }));
  const root = path.join(base, "project");
  const kit = path.join(base, "kit");
  const put = async (file, text) => {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, text);
  };
  for (const [name, text] of Object.entries(projectAgents)) await put(path.join(root, ".claude/agents", name), text);
  for (const [name, text] of Object.entries(kitAgents)) await put(path.join(kit, "plugins/core/agents", name), text);
  for (const [id, text] of Object.entries(kitSkills)) await put(path.join(kit, "plugins/core/skills", id, "SKILL.md"), text);
  await put(path.join(kit, "package.json"), '{"name":"wf-kit"}');
  if (opencode) await put(path.join(root, "opencode.json"), opencode);
  await mkdir(root, { recursive: true });
  return { root, kit };
}

const manual = "---\nname: handoff\ndescription: Writes a handoff. Use only when asked.\ndisable-model-invocation: true\n---\n\n# Handoff\n";

test("a skill description is read as one line, and only a manual skill gets a command", () => {
  assert.deepEqual(parseSkill(source.replace("tools: Read, Grep, WebFetch, WebSearch\n", "")), {
    description: "Reviews sample code and reports findings. Never edits files.",
    manual: false,
  });
  assert.equal(parseSkill(manual).manual, true);
});

test("sync writes agents from the project and the kit, commands for manual skills, and the skills path", async (t) => {
  const { root, kit } = await fixture(t, {
    projectAgents: { "sample-agent.md": source },
    kitAgents: { "kit-agent.md": source.replace("name: sample-agent", "name: kit-agent") },
    kitSkills: { handoff: manual },
  });
  const first = await reconcile(root, { write: true, kitRoot: kit });
  assert.deepEqual(first.problems, []);
  assert.deepEqual((await readdir(path.join(root, ".opencode/agents"))).sort(), ["kit-agent.md", "sample-agent.md"]);
  assert.match(await readFile(path.join(root, ".opencode/commands/handoff.md"), "utf8"), /Load the `handoff` skill/);
  assert.deepEqual(JSON.parse(await readFile(path.join(root, "opencode.json"), "utf8")).skills, ["../kit/plugins/core/skills"]);
  assert.deepEqual((await reconcile(root, { kitRoot: kit })).problems, []);
});

test("an agent in both the project and the kit is refused", async (t) => {
  const { root, kit } = await fixture(t, { projectAgents: { "sample-agent.md": source }, kitAgents: { "sample-agent.md": source } });
  await assert.rejects(reconcile(root, { kitRoot: kit }), /defined in two places/);
});

test("a generated file whose source is gone is removed, and a hand-written one is left and reported", async (t) => {
  const { root, kit } = await fixture(t, { kitSkills: { handoff: manual } });
  await reconcile(root, { write: true, kitRoot: kit });
  await writeFile(path.join(root, ".opencode/commands/old.md"), "---\n# Generated by tools/ai/adapters.mjs; do not edit.\n---\n");
  await writeFile(path.join(root, ".opencode/commands/mine.md"), "---\ndescription: mine\n---\n");
  await writeFile(path.join(root, ".opencode/commands/handoff.md"), "hand-written\n");
  const result = await reconcile(root, { write: true, kitRoot: kit });
  assert.deepEqual(result.problems, [".opencode/commands/handoff.md: hand-written, and the kit would generate it; delete it"]);
  assert.deepEqual((await readdir(path.join(root, ".opencode/commands"))).sort(), ["handoff.md", "mine.md"]);
});

test("the skills path goes through node_modules when the project links the kit there", async (t) => {
  const { root, kit } = await fixture(t, { kitSkills: { handoff: manual } });
  await mkdir(path.join(root, "node_modules"), { recursive: true });
  await symlink(kit, path.join(root, "node_modules", "wf-kit"));
  await reconcile(root, { write: true, kitRoot: kit });
  assert.deepEqual(JSON.parse(await readFile(path.join(root, "opencode.json"), "utf8")).skills, ["node_modules/wf-kit/plugins/core/skills"]);
});

test("a Claude Code only project gets the deny rules but no OpenCode files", async (t) => {
  const { root, kit } = await fixture(t, { projectAgents: { "sample-agent.md": source }, kitSkills: { handoff: manual } });
  const result = await reconcile(root, { write: true, kitRoot: kit, tools: ["claude"] });
  assert.deepEqual(result.problems, []);
  const { existsSync } = await import("node:fs");
  assert.equal(existsSync(path.join(root, ".opencode")), false);
  assert.equal(existsSync(path.join(root, "opencode.json")), false);
  assert.ok(JSON.parse(await readFile(path.join(root, ".claude/settings.json"), "utf8")).permissions.deny.length > 0);
});
